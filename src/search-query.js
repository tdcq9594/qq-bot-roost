/**
 * 查询词归一化：面板「查询」页用。
 *
 * 参考 dsh-roost 的 `src/tokenize.js`（那边给 FTS5 建索引）。**那边踩过的坑
 * 这里同样适用**，只是我们没有 FTS 表，用 LIKE 直接匹配：
 *
 *   · `unicode61` 把一整串汉字当一个词，`我住在杭州` 只能整串命中——所以它
 *     索引侧做了二元组切分。我们不做索引，改用**查询侧断词**：把疑问/语气词
 *     换成空格，长句自然断成几个有意义的关键词，各自 LIKE 再 AND。
 *   · 疑问词会把主语稀释掉：搜「魂骨怎么获得」整串匹配基本命中不了；
 *     断成「魂骨」「获得」两词后，绝大部分相关消息都能中。
 *   · **只剥查询侧，不动库里原文**——文档侧任何改写都会让索引和原文对不上。
 *
 * 和那边的差别：这边没有 FTS 的 bm25，排序统一按时间倒序（`seq DESC`）。
 * 查询页要的是「筛出相关内容」，相关性用「多词全中」保证就够了。
 */

/**
 * 疑问 / 语气 / 客套词，**只在查询侧**换成空格。
 *
 * 顺序要紧：长的排前面，否则「什么时候」会先被「什么」吃掉一半。
 * 只收**多字词**——单字里除了「吗 / 呢 / 吧」这类纯语气，别的都可能是实词
 * 的一部分（「我的世界」把「的」剥掉就变成两个废词）。
 */
const QUERY_NOISE = [
  '什么时候',
  '什么样',
  '为什么',
  '怎么样',
  '是不是',
  '有没有',
  '能不能',
  '可不可以',
  '还记得',
  '记不记得',
  '告诉我',
  '我想知道',
  '帮我查',
  '帮我找',
  '帮我看看',
  '请问',
  '如何',
  '怎么',
  '什么',
  '哪些',
  '哪个',
  '哪里',
  '多少',
  '多久',
  '几点',
  '是谁',
  '谁说',
  '在哪',
  '吗',
  '呢',
  '吧',
  '呀',
  '哦',
  '嗯',
];

/** 全角标点与常见分隔符都当断点 */
const SEPARATORS = /[\s,，、;；:：!！?？。.·|/\\()（）[\]【】"'“”‘’<>《》]+/;

/**
 * 把用户输入拆成检索词。
 *
 * @param {string} raw
 * @param {number} [max] 最多几个词（SQL 参数别无限膨胀）
 * @returns {string[]} 去重后的词，按出现顺序
 */
export function splitQuery(raw, max = 6) {
  let text = String(raw ?? '').replace(/\u3000/g, ' ');
  /** 剥疑问词：替换成空格而不是删除——删除会凭空造出「骨获」这种不存在的词 */
  for (const w of QUERY_NOISE) text = text.split(w).join(' ');

  const out = [];
  for (const piece of text.split(SEPARATORS)) {
    const t = piece.trim();
    if (!t) continue;
    /** 单字几乎必然过宽（搜「我」等于搜全库），直接丢；数字和字母除外 */
    if (t.length < 2 && !/^[a-z0-9]$/i.test(t)) continue;
    if (!out.includes(t)) out.push(t);
    if (out.length >= max) break;
  }
  return out;
}
